"""Emit G-code for a pen plotter built from a 3D printer."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .config import Config
from .pipeline import path_length


@dataclass
class Stats:
    strokes: int
    pen_lifts: int
    draw_mm: float
    travel_mm: float
    minutes: float


def strokes_with_lifts(paths: list[np.ndarray], cfg: Config) -> list[tuple[np.ndarray, bool]]:
    """Pair each stroke with whether the pen must lift before it (False = gap small enough to bridge)."""
    out = []
    pos = None
    for p in paths:
        lift = pos is None or float(np.hypot(*(p[0] - pos))) > cfg.output.join_distance
        out.append((p, lift))
        pos = p[-1]
    return out


def compute_stats(paths: list[np.ndarray], cfg: Config) -> Stats:
    mc, pc = cfg.machine, cfg.pen
    pos = np.array([mc.park_x, mc.park_y])
    draw = travel = 0.0
    lifts = 0
    for p, lift in strokes_with_lifts(paths, cfg):
        hop = float(np.hypot(*(p[0] - pos)))
        if lift:
            lifts += 1
            travel += hop
        else:
            draw += hop
        draw += path_length(p)
        pos = p[-1]
    travel += float(np.hypot(*(pos - [mc.park_x, mc.park_y]))) if paths else 0.0
    z_time = lifts * 2 * (pc.up_z - pc.down_z) / pc.z_feed
    dwell = lifts * (pc.down_dwell_ms + pc.up_dwell_ms) / 60000
    minutes = draw / mc.draw_feed + travel / mc.travel_feed + z_time + dwell
    return Stats(len(paths), lifts, draw, travel, minutes)


def check_bounds(paths: list[np.ndarray], cfg: Config) -> None:
    mc = cfg.machine
    if not paths:
        return
    pts = np.vstack(paths)
    lo, hi = pts.min(axis=0), pts.max(axis=0)
    tol = 1e-6
    if (
        lo[0] < mc.origin_x - tol
        or lo[1] < mc.origin_y - tol
        or hi[0] > mc.origin_x + mc.bed_width + tol
        or hi[1] > mc.origin_y + mc.bed_height + tol
    ):
        raise ValueError(f"toolpath ({lo[0]:.2f},{lo[1]:.2f})-({hi[0]:.2f},{hi[1]:.2f}) leaves the bed")


def generate(paths: list[np.ndarray], cfg: Config, source: str = "") -> str:
    check_bounds(paths, cfg)
    mc, pc = cfg.machine, cfg.pen
    stats = compute_stats(paths, cfg)
    out: list[str] = []
    emit = out.append

    def pen(down: bool) -> None:
        template, z, dwell = (
            (pc.down_gcode, pc.down_z, pc.down_dwell_ms) if down else (pc.up_gcode, pc.up_z, pc.up_dwell_ms)
        )
        emit(template.format(z=z, z_feed=pc.z_feed))
        if dwell > 0:
            emit(f"G4 P{int(dwell)}")

    emit(f"; generated by image-to-gcode{f' from {source}' if source else ''}")
    emit(f"; bed {mc.bed_width} x {mc.bed_height} mm at origin ({mc.origin_x}, {mc.origin_y})")
    emit(f"; pen down Z={pc.down_z}  pen up Z={pc.up_z}  safe Z={pc.safe_z}")
    emit(f"; {stats.strokes} strokes, {stats.pen_lifts} pen lifts, "
         f"{stats.draw_mm / 1000:.2f} m drawn, {stats.travel_mm / 1000:.2f} m travel, "
         f"~{stats.minutes:.1f} min")
    emit("G21 ; millimetres")
    emit("G90 ; absolute positioning")
    emit(mc.start_gcode)
    emit(f"G1 Z{pc.safe_z:.3f} F{pc.z_feed:.0f} ; raise to safe height")

    for p, lift in strokes_with_lifts(paths, cfg):
        x, y = p[0]
        if lift:
            pen(False)
            emit(f"G0 X{x:.3f} Y{y:.3f} F{mc.travel_feed:.0f}")
            pen(True)
        else:
            emit(f"G1 X{x:.3f} Y{y:.3f} F{mc.draw_feed:.0f}")
        emit(f"G1 X{p[1][0]:.3f} Y{p[1][1]:.3f} F{mc.draw_feed:.0f}")
        out.extend(f"G1 X{x:.3f} Y{y:.3f}" for x, y in p[2:])

    pen(False)
    emit(f"G1 Z{pc.safe_z:.3f} F{pc.z_feed:.0f} ; raise to safe height")
    emit(f"G0 X{mc.park_x:.3f} Y{mc.park_y:.3f} F{mc.travel_feed:.0f} ; park")
    emit(mc.end_gcode)
    return "\n".join(out) + "\n"
